using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
namespace FargosPhantasmMode.SourceGenerator.PBuffIDTable;

[Generator]
public class PBuffIDGenerator : IIncrementalGenerator
{
    private const string ModBuffMetadataName = "Terraria.ModLoader.ModBuff";
    public void Initialize(IncrementalGeneratorInitializationContext initContext)
    {
        var buffs = initContext.SyntaxProvider.CreateSyntaxProvider(
        static (node, _) =>
            node is ClassDeclarationSyntax
            {
                BaseList: not null
            },
        static (ctx, _) =>
        {
            var declaration = (ClassDeclarationSyntax)ctx.Node;

            if (ctx.SemanticModel.GetDeclaredSymbol(declaration) is not INamedTypeSymbol symbol)
                return null;

            // 排除抽象类和开放泛型类。
            if (symbol.IsAbstract || symbol.IsGenericType)
                return null;
            // 只处理 public 类。
            if (symbol.DeclaredAccessibility != Accessibility.Public)
                return null;

            // 检查整个继承链，而不只检查直接基类。
            var baseType = symbol.BaseType;

            while (baseType is not null && baseType.ToDisplayString() != ModBuffMetadataName)
                baseType = baseType.BaseType;

            if (baseType is null)
                return null;

            // 仅处理简单、合法且非关键字的类名。
            var name = symbol.Name;

            if (!SyntaxFacts.IsValidIdentifier(name) || SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None)
                return null;

            return new ModTypeInfo(name, symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
        });
        //var externalBuffs = initContext.CompilationProvider.Select(static (compilation, _) => RegisterIDTable.ScanAssembly(compilation, "FargowiltasSouls", ModBuffMetadataName));

        var collectedBuffs = buffs
            .Where(static buff => buff is not null)
            .Select(static (buff, _) => buff!)
            .Collect();

        initContext.RegisterSourceOutput(collectedBuffs,
            static (spc, items) =>
            {
                var uniqueBuffs = items
                    .GroupBy(static buff => buff.Name)
                    .Where(static group => group.Count() == 1)
                    .Select(static group => group.First())
                    .OrderBy(static buff => buff.Name)
                    .ToArray();

                var source = new StringBuilder();

                source.AppendLine("// <auto-generated/>");
                source.AppendLine(
                    "public static class PBuffID");
                source.AppendLine("{");

                foreach (var buff in uniqueBuffs)
                {
                    source.AppendLine(
                        "    private static readonly " +
                        "global::System.Lazy<int> __" +
                        buff.Name + " = new(() => " +
                        "global::Terraria.ModLoader.ModContent." +
                        "BuffType<" + buff.TypeName + ">());");

                    source.AppendLine(
                        "    public static int " +
                        buff.Name + " => __" +
                        buff.Name + ".Value;");

                    source.AppendLine();
                }

                source.AppendLine("}");

                spc.AddSource(
                    "PBuffID.g.cs",
                    SourceText.From(
                        source.ToString(),
                        Encoding.UTF8));
            });
    }
}
