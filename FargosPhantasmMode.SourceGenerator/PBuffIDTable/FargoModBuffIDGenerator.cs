using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace FargosPhantasmMode.SourceGenerator.PBuffIDTable;

[Generator]
public class FargoModBuffIDGenerator : IIncrementalGenerator
{
    private const string ModBuffMetadataName = "Terraria.ModLoader.ModBuff";
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var externalBuffs = context.CompilationProvider.Select(static (compilation, _) => RegisterIDTable.ScanAssembly(compilation, "FargowiltasSouls", ModBuffMetadataName));

        context.RegisterSourceOutput(externalBuffs,
            static (spc, items) =>
            {
                var uniqueBuffs = items
                    .GroupBy(static buff => buff.Name)
                    .Where(static group => group.Count() == 1)
                    .Select(static group => group.First())
                    .OrderBy(static buff => buff.Name)
                    .ToArray();

                var source = new StringBuilder();

                source.AppendLine("// <auto-generated/>");
                source.AppendLine(
                    "public static class FBuffID");
                source.AppendLine("{");

                foreach (var buff in uniqueBuffs)
                {
                    source.AppendLine(
                        "    private static readonly " +
                        "global::System.Lazy<int> __" +
                        buff.Name + " = new(() => " +
                        "global::Terraria.ModLoader.ModContent." +
                        "BuffType<" + buff.TypeName + ">());");

                    source.AppendLine(
                        "    public static int " +
                        buff.Name + " => __" +
                        buff.Name + ".Value;");

                    source.AppendLine();
                }

                source.AppendLine("}");

                spc.AddSource(
                    "FBuffID.g.cs",
                    SourceText.From(
                        source.ToString(),
                        Encoding.UTF8));
            });
    }
}
