using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace FargosPhantasmMode.SourceGenerator.PProjIDTable
{
    [Generator]
    public class FargoModProjIDGenerator : IIncrementalGenerator
    {
        private const string ModTypeMetadataName = "Terraria.ModLoader.ModProjectile";
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var externalBuffs = context.CompilationProvider.Select(static (compilation, _) => RegisterIDTable.ScanAssembly(compilation, "FargowiltasSouls", ModTypeMetadataName));

            context.RegisterSourceOutput(externalBuffs,
                static (spc, items) =>
                {
                    var uniqueBuffs = items
                        .GroupBy(static buff => buff.Name)
                        .Where(static group => group.Count() == 1)
                        .Select(static group => group.First())
                        .OrderBy(static buff => buff.Name)
                        .ToArray();

                    var source = new StringBuilder();

                    source.AppendLine("// <auto-generated/>");
                    source.AppendLine(
                        "public static class FProjID");
                    source.AppendLine("{");

                    foreach (var buff in uniqueBuffs)
                    {
                        source.AppendLine(
                            "    private static readonly " +
                            "global::System.Lazy<int> __" +
                            buff.Name + " = new(() => " +
                            "global::Terraria.ModLoader.ModContent." +
                            "ProjectileType<" + buff.TypeName + ">());");

                        source.AppendLine(
                            "    public static int " +
                            buff.Name + " => __" +
                            buff.Name + ".Value;");

                        source.AppendLine();
                    }

                    source.AppendLine("}");

                    spc.AddSource(
                        "FProjID.g.cs",
                        SourceText.From(
                            source.ToString(),
                            Encoding.UTF8));
                });
        }
    }
}
